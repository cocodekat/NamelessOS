// Lowercase letters aren't hand-drawn separately — they just reuse the
// uppercase shapes. Still fully readable, just no distinct lowercase
// forms yet. Called once from fb_console_init().
static void font8x8_apply_lowercase(void) {
    for (int ch = 'a'; ch <= 'z'; ch++) {
        for (int i = 0; i < 8; i++) {
            font8x8[ch][i] = font8x8[ch - 'a' + 'A'][i];
        }
    }
}

